"""
Sphinx extension of the BBarolo documentation: the parameters of a task, from the keyword table of the
code (bbarolo/keywords.py), so that the pages always list every keyword with its default.

    ```{bbparams} 3DFIT
    :group: Rings
    ```

renders the keywords of the task 3DFIT (ALL: the general parameters, used by every task), each with its
aliases, type, default and description, in sections (Keyword.group_for(task), in the order of
keywords_doc.GROUPS; the keywords of a section in the order of the table). Every keyword gets a target,
par-<task>-<keyword> in lower case (e.g. par-3dfit-free), for references such as
{ref}`FREE <par-3dfit-free>`. The description is Keyword.doc (Markdown) if the keyword has one, else
its one-line help. With :group:, only the keywords of that section (the parameter pages of the tasks,
generated by write_parameter_pages, have a heading and a directive per section).

write_parameter_pages(srcdir, pages) writes tasks/<folder>/parameters.md for each (folder, task, title) of
pages, with a section per group; conf.py calls it at every build, so the pages follow the code.
"""

import os


from docutils import nodes
from docutils.statemachine import StringList
from sphinx.util.docutils import SphinxDirective

_TYPES = {"str": "text", "lstr": "text", "ustr": "text", "pos": "text", "flag": "true or false",
          "int": "integer", "float": "number", "cdens": "number", "flagorint": "integer (or true/false)",
          "ivec": "list of integers", "fvec": "list of numbers", "fvec2": "list of numbers",
          "fvec3": "list of numbers", "ivec6": "list of integers"}


def _keywords(task):
    from bbarolo import keywords as K
    if task == "ALL":
        return [k for k in K.KEYWORDS if k.tasks[0] == "ALL"]
    return K.keywords_for(task)


def _default(kw, task):
    """The default as shown: the value (in backticks), the default in words (kw.default_text), or None."""
    from bbarolo import keywords as K
    from bbarolo.params import _default_param
    tdef = K.TASK_DEFAULTS.get(task, {})
    if kw.name in tdef:
        return f"`{K._fmtval(tdef[kw.name])}`"
    if kw.default_text:
        return kw.default_text
    s = K._fmtval(kw.value(_default_param()))
    return None if s in ("-1", '""', "") else f"`{s}`"


def _type(kw):
    from bbarolo.params import _RING_KEYS
    if kw.name in _RING_KEYS:
        return "a number, one number per ring, or file(name,column)"
    return _TYPES.get(kw.kind, kw.kind)


def task_groups(task):
    """{group: [keywords]} of a task, the groups in the order of keywords_doc.GROUPS."""
    from bbarolo.keywords_doc import GROUPS
    groups = {}
    for kw in _keywords(task):
        g = kw.group_for(task) or "Options"
        if g not in GROUPS:
            raise ValueError(f"bbparams: unknown group {g!r} of {kw.name}")
        groups.setdefault(g, []).append(kw)
    return {g: groups[g] for g in sorted(groups, key=GROUPS.index)}


def write_parameter_pages(srcdir, pages):
    """tasks/<folder>/parameters.md for each (folder, task, title) of pages (written only if changed)."""
    for folder, task, title in pages:
        lines = [f"# {title}: parameters", "",
                 f"The parameters of {task}: the keywords of the parameter files (case-insensitive; in Python, "
                 "the same names as arguments). " + ("These are accepted by every task." if task == "ALL" else
                                                     "The {doc}`general parameters <../general>` are accepted by "
                                                     "every task."), ""]
        if task == "ALL":
            lines[0] = "# General parameters"
            lines[2] = ("The parameters accepted by every task: the input cube, the outputs, the messages and the "
                        "computation. Keywords are case-insensitive; in Python, the same names are arguments.")
        for g in task_groups(task):
            lines += [f"## {g}", "", f"```{{bbparams}} {task}", f":group: {g}", "```", ""]
        text = "<!-- Generated from bbarolo/keywords.py and keywords_doc.py by docs/_ext/bbparams.py: do not "\
               "edit. -->\n" + "\n".join(lines)
        fn = os.path.join(srcdir, "tasks", *(folder.split("/")), "parameters.md") if folder else \
            os.path.join(srcdir, "tasks", "general.md")
        old = open(fn).read() if os.path.isfile(fn) else None
        if old != text:
            os.makedirs(os.path.dirname(fn), exist_ok=True)
            with open(fn, "w") as f:
                f.write(text)


class BBParams(SphinxDirective):
    required_arguments = 1
    has_content = False
    option_spec = {"group": str}

    def run(self):
        from bbarolo.keywords_doc import GROUPS
        task = self.arguments[0].strip().upper()
        kws = _keywords(task)
        if not kws:
            raise self.error(f"bbparams: no keywords for task {task!r}")
        only = self.options.get("group")
        if only is not None:
            sel = [kw for kw in kws if (kw.group_for(task) or "Options") == only.strip()]
            if not sel:
                raise self.error(f"bbparams: no keywords of {task} in the group {only!r}")
            return [self._list(task, sel)]
        groups = {}
        for kw in kws:
            g = kw.group_for(task) or "Options"
            if g not in GROUPS:
                raise self.error(f"bbparams: unknown group {g!r} of {kw.name}")
            groups.setdefault(g, []).append(kw)
        result = []
        for g in sorted(groups, key=GROUPS.index):
            if len(groups) > 1:
                result.append(nodes.rubric(text=g, classes=["bbparams-group"]))
            result.append(self._list(task, groups[g]))
        return result

    def _list(self, task, kws):
        out = nodes.definition_list(classes=["bbparams"])
        for kw in kws:
            item = nodes.definition_list_item()
            tid = nodes.make_id(f"par-{task}-{kw.name}".lower())
            term = nodes.term()
            term += nodes.literal(text=kw.name)
            if kw.aliases:
                term += nodes.inline(text="  (also " + ", ".join(kw.aliases) + ")", classes=["bbparams-aliases"])
            term["ids"].append(tid)
            self.env.get_domain("std").note_hyperlink_target(tid, self.env.docname, tid, kw.name)
            item += term
            body = nodes.definition()
            text = (getattr(kw, "doc", None) or kw.help.rstrip(".") + ".").strip()
            meta = [f"*Type:* {_type(kw)}"]
            d = _default(kw, task)
            meta.append(f"*Default:* {d}" if d is not None else "*Default:* not set")
            lines = text.splitlines() + ["", " · ".join(meta)]
            self.state.nested_parse(StringList(lines, source=f"keyword {kw.name}"), self.content_offset, body)
            item += body
            out += item
        return out


def setup(app):
    app.add_directive("bbparams", BBParams)
    return {"version": "1.0", "parallel_read_safe": True, "parallel_write_safe": True}
